"""Read-only profiling of the Olist source CSVs (Phase 1 support script).

Usage (from repo root):
    python 02_Data/profiling/profile_source.py

Reads 02_Data/raw_data/*.csv, never modifies them, and writes
02_Data/profiling/profiling_report.md and profiling_summary.json.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "02_Data" / "raw_data"
OUT = Path(__file__).resolve().parent

FILES = {
    "customers": "olist_customers_dataset.csv",
    "geolocation": "olist_geolocation_dataset.csv",
    "order_items": "olist_order_items_dataset.csv",
    "payments": "olist_order_payments_dataset.csv",
    "reviews": "olist_order_reviews_dataset.csv",
    "orders": "olist_orders_dataset.csv",
    "products": "olist_products_dataset.csv",
    "sellers": "olist_sellers_dataset.csv",
    "category_translation": "product_category_name_translation.csv",
}
DATE_COLS = {
    "orders": ["order_purchase_timestamp", "order_approved_at", "order_delivered_carrier_date",
               "order_delivered_customer_date", "order_estimated_delivery_date"],
    "order_items": ["shipping_limit_date"],
    "reviews": ["review_creation_date", "review_answer_timestamp"],
}

lines, summary = [], {}


def md(s=""):
    lines.append(s)


def table(df):
    df = df.copy()
    md("| " + " | ".join(map(str, df.columns)) + " |")
    md("|" + "---|" * len(df.columns))
    for row in df.itertuples(index=False):
        md("| " + " | ".join(map(str, row)) + " |")
    md()


def pct(a, b):
    return f"{100 * a / b:.2f}%" if b else "n/a"


# ---------------------------------------------------------------- load
d = {}
for k, f in FILES.items():
    d[k] = pd.read_csv(RAW / f, parse_dates=DATE_COLS.get(k, []), low_memory=False)

md("# Olist Source Data Profiling Report")
md()
md("Generated by `02_Data/profiling/profile_source.py` (read-only). "
   "Source: Kaggle `olistbr/brazilian-ecommerce`, version 2.")
md()

# ---------------------------------------------------------------- 1. files
md("## 1. Files and row counts")
rows = []
for k, f in FILES.items():
    df = d[k]
    rows.append([f, f"{len(df):,}", len(df.columns), f"{df.duplicated().sum():,}"])
    summary.setdefault(k, {})["rows"] = int(len(df))
    summary[k]["full_row_duplicates"] = int(df.duplicated().sum())
table(pd.DataFrame(rows, columns=["File", "Rows", "Columns", "Fully duplicated rows"]))

# ---------------------------------------------------------------- 2. columns
md("## 2. Columns, types and nulls")
for k, f in FILES.items():
    df = d[k]
    md(f"### {f}")
    rows = []
    for c in df.columns:
        n = int(df[c].isna().sum())
        rows.append([c, str(df[c].dtype), f"{df[c].nunique(dropna=True):,}", f"{n:,}", pct(n, len(df))])
        summary[k].setdefault("nulls", {})[c] = n
    table(pd.DataFrame(rows, columns=["Column", "Pandas dtype", "Distinct", "Nulls", "Null %"]))

# ---------------------------------------------------------------- 3. keys
md("## 3. Candidate key uniqueness")
keys = [
    ("orders", ["order_id"]),
    ("customers", ["customer_id"]),
    ("customers", ["customer_unique_id"]),
    ("order_items", ["order_id", "order_item_id"]),
    ("payments", ["order_id", "payment_sequential"]),
    ("reviews", ["review_id"]),
    ("reviews", ["order_id"]),
    ("reviews", ["review_id", "order_id"]),
    ("products", ["product_id"]),
    ("sellers", ["seller_id"]),
    ("category_translation", ["product_category_name"]),
    ("geolocation", ["geolocation_zip_code_prefix"]),
]
rows = []
for t, cols in keys:
    df = d[t]
    dup = int(df.duplicated(subset=cols).sum())
    rows.append([t, " + ".join(cols), f"{len(df):,}", f"{len(df) - dup:,}", f"{dup:,}",
                 "Yes" if dup == 0 else "No"])
    summary.setdefault("keys", {})[f"{t}:{'+'.join(cols)}"] = {"duplicates": dup}
table(pd.DataFrame(rows, columns=["Table", "Key", "Rows", "Distinct keys", "Duplicate keys", "Unique?"]))

# ---------------------------------------------------------------- 4. FK coverage
md("## 4. Relationship (foreign-key) coverage")
geo_zips = set(d["geolocation"]["geolocation_zip_code_prefix"])
fks = [
    ("orders.customer_id -> customers.customer_id", d["orders"]["customer_id"], set(d["customers"]["customer_id"])),
    ("customers.customer_id -> orders.customer_id", d["customers"]["customer_id"], set(d["orders"]["customer_id"])),
    ("order_items.order_id -> orders", d["order_items"]["order_id"], set(d["orders"]["order_id"])),
    ("order_items.product_id -> products", d["order_items"]["product_id"], set(d["products"]["product_id"])),
    ("order_items.seller_id -> sellers", d["order_items"]["seller_id"], set(d["sellers"]["seller_id"])),
    ("payments.order_id -> orders", d["payments"]["order_id"], set(d["orders"]["order_id"])),
    ("reviews.order_id -> orders", d["reviews"]["order_id"], set(d["orders"]["order_id"])),
    ("products.product_category_name -> translation",
     d["products"]["product_category_name"].dropna(), set(d["category_translation"]["product_category_name"])),
    ("customers.zip_prefix -> geolocation", d["customers"]["customer_zip_code_prefix"], geo_zips),
    ("sellers.zip_prefix -> geolocation", d["sellers"]["seller_zip_code_prefix"], geo_zips),
]
rows = []
for name, s, ref in fks:
    miss = int((~s.isin(ref)).sum())
    rows.append([name, f"{len(s):,}", f"{miss:,}", pct(miss, len(s))])
    summary.setdefault("fk_missing", {})[name] = miss
table(pd.DataFrame(rows, columns=["Relationship", "Child rows", "Unmatched", "Unmatched %"]))

untranslated = sorted(set(d["products"]["product_category_name"].dropna())
                      - set(d["category_translation"]["product_category_name"]))
md(f"Categories present in products but missing from translation: {untranslated}")
md()

# ---------------------------------------------------------------- 5. cardinality per order
md("## 5. Cardinality per order (join-multiplication risk)")
o = d["orders"]
items_per = d["order_items"].groupby("order_id").size()
pay_per = d["payments"].groupby("order_id").size()
rev_per = d["reviews"].groupby("order_id").size()
rows = []
for name, s in [("order_items", items_per), ("payments", pay_per), ("reviews", rev_per)]:
    rows.append([name, f"{s.size:,}", f"{o['order_id'].isin(s.index).eq(False).sum():,}",
                 f"{(s > 1).sum():,}", int(s.max()), f"{s.mean():.3f}"])
table(pd.DataFrame(rows, columns=["Child table", "Orders with rows", "Orders with no rows",
                                  "Orders with >1 row", "Max rows per order", "Mean rows per order"]))

j = d["order_items"].merge(d["payments"], on="order_id")
both = items_per.index.intersection(pay_per.index)
multi_both = int(((items_per.loc[both] > 1) & (pay_per.loc[both] > 1)).sum())
true_price = d["order_items"]["price"].sum()
true_pay = d["payments"]["payment_value"].sum()
md(f"- Naive join order_items x payments produces **{len(j):,} rows** "
   f"(vs {len(d['order_items']):,} items and {len(d['payments']):,} payments).")
md(f"- Orders with >1 item AND >1 payment: {multi_both:,}.")
md(f"- SUM(price) correct = {true_price:,.2f}; after naive join = {j['price'].sum():,.2f} "
   f"(inflated by {j['price'].sum() - true_price:,.2f}).")
md(f"- SUM(payment_value) correct = {true_pay:,.2f}; after naive join = {j['payment_value'].sum():,.2f} "
   f"(inflated by {j['payment_value'].sum() - true_pay:,.2f}).")
md()
summary["join_risk"] = {"items_x_payments_rows": int(len(j)), "orders_multi_item_multi_payment": multi_both}

sellers_per = d["order_items"].groupby("order_id")["seller_id"].nunique()
md(f"- Orders with more than one seller: {(sellers_per > 1).sum():,} "
   f"({pct((sellers_per > 1).sum(), sellers_per.size)} of orders with items).")
md(f"- Orders containing the same product on more than one line (quantity > 1): "
   f"{(d['order_items'].groupby(['order_id', 'product_id']).size() > 1).groupby(level=0).any().sum():,}.")
md()

# ---------------------------------------------------------------- 6. payment vs item value
md("## 6. Item value vs payment value reconciliation (per order)")
iv = d["order_items"].groupby("order_id").agg(price=("price", "sum"), freight=("freight_value", "sum"))
iv["item_total"] = iv["price"] + iv["freight"]
pv = d["payments"].groupby("order_id")["payment_value"].sum()
rec = iv.join(pv, how="inner")
rec["diff"] = (rec["payment_value"] - rec["item_total"]).round(2)
md(f"- Orders compared: {len(rec):,}")
md(f"- |payment - (price + freight)| <= 0.01: {(rec['diff'].abs() <= 0.01).sum():,} "
   f"({pct((rec['diff'].abs() <= 0.01).sum(), len(rec))})")
md(f"- payment > item total by more than 0.01: {(rec['diff'] > 0.01).sum():,}; "
   f"payment < item total by more than 0.01: {(rec['diff'] < -0.01).sum():,}")
md(f"- Totals: SUM(price) = {iv['price'].sum():,.2f}; SUM(freight) = {iv['freight'].sum():,.2f}; "
   f"SUM(payment_value) = {pv.sum():,.2f}")
md()
summary["reconciliation"] = {"orders": int(len(rec)), "match_within_0_01": int((rec["diff"].abs() <= 0.01).sum())}

# ---------------------------------------------------------------- 7. orders lifecycle
md("## 7. Order status and lifecycle timestamps")
st = o["order_status"].value_counts()
table(pd.DataFrame({"order_status": st.index, "orders": [f"{v:,}" for v in st.values],
                    "share": [pct(v, len(o)) for v in st.values]}))
summary["order_status"] = {k: int(v) for k, v in st.items()}

rows = []
for c in DATE_COLS["orders"]:
    rows.append([c, str(o[c].min()), str(o[c].max()), f"{o[c].isna().sum():,}"])
table(pd.DataFrame(rows, columns=["Timestamp", "Min", "Max", "Nulls"]))

dlv = o[o["order_status"] == "delivered"]
md(f"- Delivered orders missing delivered_customer_date: {dlv['order_delivered_customer_date'].isna().sum():,}")
md(f"- Delivered orders missing approved_at: {dlv['order_approved_at'].isna().sum():,}; "
   f"missing carrier date: {dlv['order_delivered_carrier_date'].isna().sum():,}")
nd = o[o["order_status"] != "delivered"]
md(f"- Non-delivered orders that nevertheless have delivered_customer_date: "
   f"{nd['order_delivered_customer_date'].notna().sum():,}")
seq_bad = {
    "approved < purchase": (o["order_approved_at"] < o["order_purchase_timestamp"]).sum(),
    "carrier < approved": (o["order_delivered_carrier_date"] < o["order_approved_at"]).sum(),
    "delivered < carrier": (o["order_delivered_customer_date"] < o["order_delivered_carrier_date"]).sum(),
    "delivered < purchase": (o["order_delivered_customer_date"] < o["order_purchase_timestamp"]).sum(),
}
md("- Out-of-sequence timestamps: " + "; ".join(f"{k}: {int(v):,}" for k, v in seq_bad.items()))
summary["timestamp_sequence_issues"] = {k: int(v) for k, v in seq_bad.items()}

dd = dlv.dropna(subset=["order_delivered_customer_date"])
late = dd["order_delivered_customer_date"].dt.normalize() > dd["order_estimated_delivery_date"].dt.normalize()
days = (dd["order_delivered_customer_date"] - dd["order_purchase_timestamp"]).dt.total_seconds() / 86400
md(f"- Delivered with date: {len(dd):,}; late vs estimate (date comparison): {late.sum():,} ({pct(late.sum(), len(dd))})")
md(f"- Purchase-to-delivery days: mean {days.mean():.1f}, median {days.median():.1f}, max {days.max():.1f}")
md(f"- Estimated delivery date carries a time component: "
   f"{(o['order_estimated_delivery_date'].dt.normalize() != o['order_estimated_delivery_date']).sum():,} rows")
md()
summary["delivery"] = {"delivered_with_date": int(len(dd)), "late": int(late.sum())}

md("### Orders per purchase month")
m = o["order_purchase_timestamp"].dt.to_period("M").value_counts().sort_index()
table(pd.DataFrame({"month": m.index.astype(str), "orders": [f"{v:,}" for v in m.values]}))
summary["orders_per_month"] = {str(k): int(v) for k, v in m.items()}

# ---------------------------------------------------------------- 8. customers
md("## 8. Customers")
c = d["customers"]
per_person = c.groupby("customer_unique_id")["customer_id"].nunique()
md(f"- customer_id rows: {len(c):,}; distinct customer_unique_id: {c['customer_unique_id'].nunique():,}")
md(f"- Persons with more than one customer_id (repeat buyers): {(per_person > 1).sum():,} "
   f"({pct((per_person > 1).sum(), per_person.size)})")
loc_var = c.groupby("customer_unique_id")[["customer_zip_code_prefix", "customer_city", "customer_state"]].nunique()
md(f"- Persons whose zip prefix differs across orders: {(loc_var['customer_zip_code_prefix'] > 1).sum():,}; "
   f"state differs: {(loc_var['customer_state'] > 1).sum():,}")
md(f"- Distinct customer states: {c['customer_state'].nunique()}; distinct cities: {c['customer_city'].nunique():,}")
md()
summary["customers"] = {"unique_persons": int(c["customer_unique_id"].nunique()),
                        "repeat_persons": int((per_person > 1).sum())}

# ---------------------------------------------------------------- 9. products / sellers
md("## 9. Products and sellers")
p = d["products"]
md(f"- Products with NULL category: {p['product_category_name'].isna().sum():,}; "
   f"distinct categories: {p['product_category_name'].nunique()}")
md(f"- Products with NULL weight/dimensions: {p['product_weight_g'].isna().sum():,}")
md(f"- Column-name misspellings in source: "
   f"{[col for col in p.columns if 'lenght' in col]}")
s = d["sellers"]
md(f"- Sellers: {len(s):,}; distinct seller states: {s['seller_state'].nunique()}")
sold = d["order_items"]["seller_id"].nunique()
md(f"- Sellers with at least one order item: {sold:,}")
md(f"- Price: min {d['order_items']['price'].min():.2f}, max {d['order_items']['price'].max():,.2f}; "
   f"freight: min {d['order_items']['freight_value'].min():.2f}, max {d['order_items']['freight_value'].max():,.2f}; "
   f"zero-freight lines: {(d['order_items']['freight_value'] == 0).sum():,}")
md()

# ---------------------------------------------------------------- 10. payments
md("## 10. Payments")
pt = d["payments"]
vc = pt["payment_type"].value_counts()
table(pd.DataFrame({"payment_type": vc.index, "rows": [f"{v:,}" for v in vc.values],
                    "payment_value": [f"{pt.loc[pt.payment_type == k, 'payment_value'].sum():,.2f}" for k in vc.index]}))
md(f"- Installments: min {pt['payment_installments'].min()}, max {pt['payment_installments'].max()}; "
   f"rows with 0 installments: {(pt['payment_installments'] == 0).sum():,}")
md(f"- Rows with payment_value = 0: {(pt['payment_value'] == 0).sum():,}")
md(f"- payment_sequential max: {pt['payment_sequential'].max()}")
md()
summary["payment_types"] = {k: int(v) for k, v in vc.items()}

# ---------------------------------------------------------------- 11. reviews
md("## 11. Reviews")
r = d["reviews"]
sc = r["review_score"].value_counts().sort_index()
table(pd.DataFrame({"review_score": sc.index, "rows": [f"{v:,}" for v in sc.values],
                    "share": [pct(v, len(r)) for v in sc.values]}))
md(f"- review_id duplicated: {r['review_id'].duplicated().sum():,}; orders with >1 review: {(rev_per > 1).sum():,}")
md(f"- Reviews with comment message: {r['review_comment_message'].notna().sum():,} "
   f"({pct(r['review_comment_message'].notna().sum(), len(r))}); with title: {r['review_comment_title'].notna().sum():,}")
md(f"- review_creation_date range: {r['review_creation_date'].min()} to {r['review_creation_date'].max()}")
md(f"- Answer before creation: {(r['review_answer_timestamp'] < r['review_creation_date']).sum():,}")
md()

# ---------------------------------------------------------------- 12. geolocation
md("## 12. Geolocation")
g = d["geolocation"]
gp = g.groupby("geolocation_zip_code_prefix").size()
md(f"- Rows: {len(g):,}; distinct zip prefixes: {gp.size:,}; mean rows per prefix: {gp.mean():.1f}")
md(f"- Distinct city spellings: {g['geolocation_city'].nunique():,}")
md(f"- Latitude range {g['geolocation_lat'].min():.2f} to {g['geolocation_lat'].max():.2f}; "
   f"longitude range {g['geolocation_lng'].min():.2f} to {g['geolocation_lng'].max():.2f} "
   "(points outside Brazil indicate coordinate errors)")
md()

(OUT / "profiling_report.md").write_text("\n".join(lines), encoding="utf-8")
(OUT / "profiling_summary.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")
print("\n".join(lines))
