"""Generate the staging and warehouse DDL from their single sources of truth (Phase 2, owner: M1).

    03_ETL/staging/staging.sql      <- SOURCES in 03_ETL/etl_config.py (exact CSV headers)
    04_Data_Warehouse/warehouse.sql <- 01_Project_Documentation/phase1/build/model_spec.py

Usage:  python 03_ETL/build_sql.py          (rewrite both files)
        python 03_ETL/build_sql.py --check  (exit 1 if the committed files are out of date)
"""
import sys
from pathlib import Path

ETL = Path(__file__).resolve().parent
ROOT = ETL.parent
sys.path.insert(0, str(ETL))
sys.path.insert(0, str(ROOT / "01_Project_Documentation" / "phase1" / "build"))

import etl_config as cfg  # noqa: E402
import model_spec as m  # noqa: E402

STAGING_SQL = ETL / "staging" / "staging.sql"
WAREHOUSE_SQL = cfg.DW_DIR / "warehouse.sql"
DW = "project_dw"
STG = "project_staging"

# Business-rule CHECK constraints. Each is taken from a rule in model_spec / P1_07 Transformation_Rules
# (TR-xx) or a decision (DEC-xxx); NULL values pass a CHECK, so optional measures are not forced.
CHECKS = {
    "dim_date": ["date_key = -1 OR full_date IS NOT NULL", "month_num BETWEEN 1 AND 12",
                 "quarter_num BETWEEN 1 AND 4", "day_of_week_num BETWEEN 1 AND 7"],
    "dim_customer": ["customer_key = -1 OR customer_state IS NOT NULL"],
    "dim_seller": ["seller_key = -1 OR seller_state IS NOT NULL"],
    "dim_order_status": ["status_group IN ('Delivered', 'In progress', 'Cancelled', 'Unknown')"],
    "dim_payment_type": ["payment_method_group IN ('Card', 'Bank slip', 'Voucher', 'Unknown')"],
    "fact_order_items": ["item_price > 0", "freight_value >= 0", "item_quantity >= 1",
                         "item_gross_value = item_price + freight_value"],
    "fact_orders": ["item_count >= 0", "order_item_value >= 0", "order_freight_value >= 0",
                    "order_payment_value >= 0", "payment_count >= 0", "review_count >= 0",
                    "purchase_hour BETWEEN 0 AND 23", "is_delivered IN (0, 1)", "is_late IN (0, 1)",
                    "is_repeat_purchase IN (0, 1)", "customer_order_number >= 1",
                    "avg_review_score BETWEEN 1 AND 5",
                    "is_delivered = 1 OR (is_late IS NULL AND delivery_delay_days IS NULL)"],
    "fact_payments": ["payment_sequential >= 1", "payment_value >= 0", "payment_installments >= 1"],
    "fact_reviews": ["review_score BETWEEN 1 AND 5", "response_hours >= 0",
                     "has_comment_title IN (0, 1)", "has_comment_message IN (0, 1)"],
}

HEADER = """-- =====================================================================================
-- {title}
-- Olist Commerce360 | DL3004 Phase 2 | owner: Member 1 (Kashish Fatima)
-- GENERATED by 03_ETL/build_sql.py from {source} - do not edit by hand.
-- =====================================================================================
"""


def q(text):
    return "'" + text.replace("'", "''") + "'"


def staging_sql():
    out = [HEADER.format(title="Staging layer DDL (schema project_staging)", source="03_ETL/etl_config.py SOURCES"),
           "-- Raw landing tables: one per source CSV, every column TEXT so that no source value is",
           "-- rejected or altered on load. Typing and cleaning happen in the cleaning stage (M2).",
           "-- stg_row_id preserves the source row order for lineage. Full reload on every run.", ""]
    for file, table, expected, cols in cfg.SOURCES:
        out.append(f"DROP TABLE IF EXISTS {STG}.{table};")
        out.append(f"CREATE TABLE {STG}.{table} (")
        out.append("    stg_row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,")
        out.append(",\n".join(f"    {c} TEXT" for c in cols))
        out.append(");")
        out.append(f"COMMENT ON TABLE {STG}.{table} IS {q(f'Raw copy of {file} (expected {expected:,} rows); all columns TEXT.')};")
        out.append("")
    return "\n".join(out)


def pg_type(table, col):
    """Dimension surrogate keys are IDENTITY columns, except dim_date's YYYYMMDD smart key."""
    _name, typ, role, *_ = col
    if role == "PK" and m.TABLE[table]["kind"] == "dimension" and table != "dim_date":
        return f"{typ} GENERATED ALWAYS AS IDENTITY"
    return typ


def warehouse_sql():
    out = [HEADER.format(title="Data warehouse DDL (schema project_dw)",
                         source="01_Project_Documentation/phase1/build/model_spec.py"),
           "-- Star schema: 6 conformed dimensions + 4 fact tables (Phase 1 deliverables P1_04 - P1_07).",
           "-- Surrogate keys: IDENTITY columns (dim_date uses the YYYYMMDD smart key). The unknown member",
           "-- (key -1) is inserted by the dimension loads with OVERRIDING SYSTEM VALUE (DEC-014).",
           "-- Indexes: only those implied by PRIMARY KEY / UNIQUE constraints. Foreign-key indexes are",
           "-- intentionally left for Phase 3, which requires an EXPLAIN ANALYZE before/after comparison.",
           "-- Rebuild: tables are dropped and recreated (facts first). No CASCADE, so a dependent",
           "-- reporting view makes the rebuild fail loudly instead of being dropped silently.", ""]
    for t in reversed(m.FACTS):
        out.append(f"DROP TABLE IF EXISTS {DW}.{t['name']};")
    for t in reversed(m.DIMS):
        out.append(f"DROP TABLE IF EXISTS {DW}.{t['name']};")
    out.append("")
    for t in m.DIMS + m.FACTS:
        name = t["name"]
        lines = []
        for c in t["columns"]:
            lines.append(f"    {c[0]} {pg_type(name, c)}{'' if c[3] else ' NOT NULL'}")
        pks = [c[0] for c in t["columns"] if c[2] == "PK"]
        lines.append(f"    CONSTRAINT pk_{name} PRIMARY KEY ({', '.join(pks)})")
        for c in t["columns"]:
            if c[2] == "NK":
                lines.append(f"    CONSTRAINT uq_{name}_{c[0]} UNIQUE ({c[0]})")
        for c in t["columns"]:
            if c[2] == "FK":
                dim, pk = c[9].split(".")
                lines.append(f"    CONSTRAINT fk_{name}_{c[0]} FOREIGN KEY ({c[0]}) REFERENCES {DW}.{dim} ({pk})")
        for i, chk in enumerate(CHECKS.get(name, []), 1):
            lines.append(f"    CONSTRAINT ck_{name}_{i} CHECK ({chk})")
        out.append(f"-- {t['type']}. Grain: {t['grain']}")
        out.append(f"CREATE TABLE {DW}.{name} (")
        out.append(",\n".join(lines))
        out.append(");")
        out.append(f"COMMENT ON TABLE {DW}.{name} IS {q(t['type'] + '. Grain: ' + t['grain'])};")
        for c in t["columns"]:
            out.append(f"COMMENT ON COLUMN {DW}.{name}.{c[0]} IS {q(c[4])};")
        out.append("")
    return "\n".join(out)


def main():
    targets = {STAGING_SQL: staging_sql(), WAREHOUSE_SQL: warehouse_sql()}
    if "--check" in sys.argv:
        stale = [str(p) for p, txt in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != txt]
        if stale:
            print("Out of date (run python 03_ETL/build_sql.py):", *stale, sep="\n  ")
            sys.exit(1)
        print("SQL files are up to date.")
        return
    for p, txt in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(txt, encoding="utf-8", newline="\n")
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
