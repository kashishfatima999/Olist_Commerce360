def fact_measure_rows(t):
    return [[c[0], c[1], c[8], c[4]] for c in t["columns"] if c[2] == "M"]


def fk_rows(t):
    return [[c[0], c[9], c[4]] for c in t["columns"] if c[2] in ("FK",)]


